"""Generate the CPU decoder and firmware address constants from one map."""
import json,pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
def generate():
    values={k:int(v,0)for k,v in json.loads((ROOT/'config/soc_map.json').read_text()).items()}
    # Fixed SRAM implementation is independently range-checked by shared tests.
    if values['SHARED_BASE']!=0x10000000 or values['SHARED_END']!=0x10010000 or values['PRIVATE_BYTES']!=65536:
        raise ValueError('Changing RAM geometry requires SRAM and linker review')
    (ROOT/'rtl/soc/soc_map.vh').write_text('// Generated by scripts/generate_map.py\n'+''.join(f"`define SOC_{k} 32'h{v:08x}\n"for k,v in values.items()))
    (ROOT/'firmware/soc_map.h').write_text('// Generated by scripts/generate_map.py\n'+''.join(f'#define SOC_{k} 0x{v:08x}u\n'for k,v in values.items()))
if __name__=='__main__':generate()
